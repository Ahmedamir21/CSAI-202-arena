def q(v):
    """SQL literal for a python value."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(v)
    return "N'" + str(v).replace("'", "''") + "'"


def insert(table, cols, rows, identity=False):
    if not rows:
        return []
    out = []
    if identity:
        out.append(f"SET IDENTITY_INSERT dbo.{table} ON;")
    collist = ", ".join(cols)
    for i in range(0, len(rows), 40):
        chunk = rows[i:i + 40]
        out.append(f"INSERT INTO dbo.{table} ({collist}) VALUES")
        lines = ["    (" + ", ".join(q(c) for c in r) + ")" for r in chunk]
        out.append(",\n".join(lines) + ";")
    if identity:
        out.append(f"SET IDENTITY_INSERT dbo.{table} OFF;")
    return out


